const scenario = (
  name: string,
  fixture: string,
  overrides: Fixture,
  steps: Step[],
  geolocation?: { latitude: number; longitude: number },
): Scenario => ({
  name,
  fixture,
  overrides,
  // The React app boots later than `load` in the development server.
  steps: [{ wait: 1200 }, ...steps],
  geolocation,
});

/** Create a settings-like button and touch it, in both apps. */
const touchButton = (attribute: string, value: string): Step => ({
  eval: `(() => { const b = document.createElement('button'); b.setAttribute('${attribute}', '${value}'); document.body.append(b); b.click(); b.remove(); })()`,
});

