import type { FieldDefinition } from './field.ts';
import { ALLURES, DOUGLAS, STORM_LIGHTS, VISI } from './lists.ts';

function degreeField(key: string, label: string): FieldDefinition {
  return {
    key,
    label,
    type: 'number',
    unit: '°',
    rose: true,
    steps: [-10, -1, 1, 10],
    min: 0,
    max: 359,
    wrap: true,
    decimals: 0,
    start: 0,
    pad: 3,
  };
}

